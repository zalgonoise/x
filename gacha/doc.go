// Package gacha is a generic library for batch and long-running operations built on the transactional outbox pattern.
//
// Items of type T are marshaled into a raw form R and written durably to a repository (the outbox) by a Writer. A
// poller claims pending entries from the repository, unmarshals them and hands each one to a Handler. Its retry
// policy decides what happens on failure: a retry with backoff, or a move to the dead-letter table. A janitor purges
// completed and dead-lettered entries on a schedule, using the same poller over the repository's views.
//
// This package only holds the contracts shared by every component: the Sink, Source and Repository interfaces over
// the raw type R, the typed Writer and Handler, the Marshaler and Unmarshaler codecs with their built-in
// implementations, and the value types that flow between them (Entry, Outcome, Status and Stats). The
// implementations live in sub-packages:
//
//   - writer: the Sync and Batch (group commit) writers.
//   - poller: the Poller, its triggers and its retry policy.
//   - janitor: a poller that purges completed and dead-lettered entries.
//   - memory, postgres, mysql, sqlite: the repositories.
//   - gachatest: the conformance suite every repository must pass.
//
// # Delivery guarantees
//
// Delivery is at-least-once. A claim durably increments the entry's attempt count and leases it before the handler
// runs, so a crash or a panic mid-handler is always accounted for: once the lease expires, another claim picks the
// entry up again. Handlers must therefore be idempotent. The entry's ID, available through IDFromContext, is a good
// idempotency key.
//
// Entry IDs are UUIDv7 values generated by the repository on write. They are unique across streams and processes,
// and they sort by creation time.
